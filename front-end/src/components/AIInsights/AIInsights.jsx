import "./styles.css";

import React, { useEffect, useState } from "react";
import { API } from "../../api-service";

const DIRECTION = {
  up: { icon: "▲", label: "higher than usual", cls: "ai-up" },
  down: { icon: "▼", label: "lower than usual", cls: "ai-down" },
  same: { icon: "●", label: "about the same as usual", cls: "ai-same" },
};

const AIInsights = ({ accessToken }) => {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    API.fetchAIInsights(accessToken, setData).finally(() => setLoading(false));
  }, [accessToken]);

  if (loading) return <div className='ai-card ai-loading'>Analysing your spending…</div>;
  if (!data) return null;

  const { prediction, summary, insights, prediction_explanation, tip, ai_error } = data;
  const dir = DIRECTION[prediction?.direction];
  const cur = summary?.currency || "€";

  return (
    <div className='ai-card'>
      <h5>AI spending insights</h5>

      {dir ? (
        <div className={`ai-prediction ${dir.cls}`}>
          <span className='ai-arrow'>{dir.icon}</span>
          <div>
            <strong>
              This month is on track to be {dir.label} ({prediction.change_percent > 0 ? "+" : ""}
              {prediction.change_percent}%)
            </strong>
            <div className='ai-sub'>
              Projected {cur}
              {prediction.projected_month_total} vs usual {cur}
              {prediction.usual_month_total} · {prediction.confidence} confidence
            </div>
          </div>
        </div>
      ) : (
        <p className='ai-sub'>{prediction?.reason}</p>
      )}

      {prediction_explanation && <p>{prediction_explanation}</p>}

      {insights?.length > 0 && (
        <ul>
          {insights.map((text, i) => (
            <li key={i}>{text}</li>
          ))}
        </ul>
      )}

      {tip && <p className='ai-tip'>💡 {tip}</p>}
      {ai_error && <p className='ai-sub'>{ai_error}</p>}
      <p className='ai-disclaimer'>Generated by AI from your expense data. Estimates, not financial advice.</p>
    </div>
  );
};

export default AIInsights;
